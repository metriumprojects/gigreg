const COUNTRY_LOOKUP = new Map(
  COUNTRIES.map((country) => [country.toLowerCase(), country])
);

export const resolveCountry = (value) => {
  if (typeof value !== "string") return null;
  const normalized = value.trim().replace(/\s+/g, " ").toLowerCase();
  if (!normalized) return null;
  return COUNTRY_LOOKUP.get(normalized) || COUNTRY_ALIASES[normalized] || null;
};

export const isValidCountry = (value) => Boolean(resolveCountry(value));
